public class length {

    public static void main(String[] args) {
        
        int[] a = {10,20,30};

        //FOOR LOOP-
        for(int i = 0; i<3; i++){
            System.out.println(a[i]);
        }

        //FOR-EACH LOOP.
        for (int i : a) {
            System.out.println(i);
        }
    }
    
}
